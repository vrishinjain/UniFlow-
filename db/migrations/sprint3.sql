BEGIN;

CREATE TABLE public.courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    code TEXT NOT NULL,
    term TEXT NOT NULL,
    faculty_id BIGINT NOT NULL REFERENCES public.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.course_enrollments (
    course_id BIGINT NOT NULL REFERENCES public.courses(id),
    student_id BIGINT NOT NULL REFERENCES public.users(id),
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (course_id, student_id)
);

ALTER TABLE public.projects
    DROP CONSTRAINT projects_status_check;

UPDATE public.projects SET status = 'pending' WHERE status = 'submitted';
UPDATE public.projects SET status = 'revision_requested' WHERE status = 'under_review';
UPDATE public.projects SET status = 'accepted' WHERE status = 'approved';

ALTER TABLE public.projects
    ALTER COLUMN status SET DEFAULT 'pending';

ALTER TABLE public.projects
    ADD CONSTRAINT projects_status_check
    CHECK (status IN ('pending', 'revision_requested', 'accepted', 'rejected'));

CREATE TABLE public.project_reviews (
    project_id BIGINT NOT NULL REFERENCES public.projects(id),
    actor_id BIGINT NOT NULL REFERENCES public.users(id),
    action TEXT NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE public.project_course_visibility (
    project_id BIGINT NOT NULL REFERENCES public.projects(id),
    course_id BIGINT NOT NULL REFERENCES public.courses(id),
    shared_by BIGINT NOT NULL REFERENCES public.users(id),
    shared_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMIT;
