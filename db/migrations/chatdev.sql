-- Team chat: one chat per project now, course-wide chats later.
-- Additive only: creates new tables and indexes, changes nothing existing.
-- Apply to chat-dev first. At release, apply to the live branch after any
-- seed.sql run (seed.sql TRUNCATEs users/projects, which these tables reference).
--
-- Rollback (only if no chat data needs keeping):
--   DROP TABLE public.chat_message, public.chat_channel_project, public.chat_channel;
BEGIN;

CREATE TABLE public.chat_channel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope TEXT NOT NULL,
    course BIGINT REFERENCES public.courses(id),
    project BIGINT REFERENCES public.projects(id),
    name TEXT,
    created_by BIGINT REFERENCES public.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    archived_at TIMESTAMPTZ,
    CONSTRAINT chat_channel_scope_check
        CHECK (scope IN ('project', 'course_projects', 'course')),
    CONSTRAINT chat_channel_scope_fields_check CHECK (
        (scope = 'project' AND project IS NOT NULL AND course IS NULL)
        OR (scope IN ('course_projects', 'course')
            AND course IS NOT NULL AND project IS NULL
            AND name IS NOT NULL AND length(btrim(name)) BETWEEN 1 AND 100
            AND created_by IS NOT NULL)
    )
);

-- Exactly one chat per project.
CREATE UNIQUE INDEX chat_channel_one_per_project_idx
    ON public.chat_channel (project) WHERE scope = 'project';

CREATE INDEX chat_channel_course_idx
    ON public.chat_channel (course) WHERE course IS NOT NULL;

-- Projects included in a 'course_projects' channel (unused until course chats ship).
CREATE TABLE public.chat_channel_project (
    channel BIGINT NOT NULL REFERENCES public.chat_channel(id),
    project BIGINT NOT NULL REFERENCES public.projects(id),
    PRIMARY KEY (channel, project)
);

CREATE TABLE public.chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel BIGINT NOT NULL REFERENCES public.chat_channel(id),
    sender BIGINT NOT NULL REFERENCES public.users(id),
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    deleted_by BIGINT REFERENCES public.users(id),
    CONSTRAINT chat_message_body_length_check
        CHECK (length(btrim(body)) BETWEEN 1 AND 2000),
    CONSTRAINT chat_message_deleted_pair_check
        CHECK ((deleted_at IS NULL) = (deleted_by IS NULL))
);

-- Paging and polling: "messages in this channel with id > / < N".
CREATE INDEX chat_message_channel_id_idx
    ON public.chat_message (channel, id);

-- Polling for deletions since the last check.
CREATE INDEX chat_message_channel_deleted_idx
    ON public.chat_message (channel, deleted_at) WHERE deleted_at IS NOT NULL;

-- Per-sender rate limit lookup.
CREATE INDEX chat_message_sender_created_idx
    ON public.chat_message (sender, created_at);

COMMIT;
