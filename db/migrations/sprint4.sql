BEGIN;

CREATE TABLE public.milestone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project BIGINT NOT NULL REFERENCES public.projects(id),
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    due_date DATE,
    created_by BIGINT NOT NULL REFERENCES public.users(id)
);

CREATE TABLE public.student_preference (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student BIGINT NOT NULL REFERENCES public.users(id),
    project BIGINT NOT NULL REFERENCES public.projects(id),
    course BIGINT NOT NULL REFERENCES public.courses(id),
    rank INTEGER NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT student_preference_student_project_key
        UNIQUE (student, project),
    CONSTRAINT student_preference_student_rank_key
        UNIQUE (student, rank)
);

CREATE TABLE public.project_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student BIGINT NOT NULL REFERENCES public.users(id),
    project BIGINT NOT NULL REFERENCES public.projects(id),
    course BIGINT NOT NULL REFERENCES public.courses(id),
    assigned_by BIGINT NOT NULL REFERENCES public.users(id),
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT project_assignment_student_course_key
        UNIQUE (student, course)
);

CREATE TABLE public.ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project BIGINT NOT NULL REFERENCES public.projects(id),
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'To Do',
    priority TEXT NOT NULL,
    assignee BIGINT REFERENCES public.users(id),
    milestone BIGINT REFERENCES public.milestone(id),
    created_by BIGINT NOT NULL REFERENCES public.users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ticket_status_check
        CHECK (status IN ('To Do', 'In Progress', 'Review', 'Done'))
);

ALTER TABLE public.courses
    ADD COLUMN preferences_open BOOLEAN NOT NULL DEFAULT FALSE;

COMMIT;
